CREATE TABLE IF NOT EXISTS "AuditLogs" (
    "Id" uuid NOT NULL,
    "ActorUserId" character varying(450) NOT NULL,
    "ActorEmail" character varying(160) NOT NULL,
    "ActorRole" character varying(64) NOT NULL,
    "Action" character varying(128) NOT NULL,
    "TargetType" character varying(128),
    "TargetId" character varying(450),
    "Details" text,
    "IpAddress" character varying(64),
    "CreatedAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_AuditLogs" PRIMARY KEY ("Id")
);

CREATE TABLE IF NOT EXISTS "OtpCodes" (
    "Id" uuid NOT NULL,
    "UserId" text,
    "Recipient" character varying(160) NOT NULL,
    "CodeHash" character varying(128) NOT NULL,
    "Purpose" integer NOT NULL,
    "CreatedAt" timestamp with time zone NOT NULL,
    "ExpiresAt" timestamp with time zone NOT NULL,
    "ConsumedAt" timestamp with time zone,
    "AttemptCount" integer NOT NULL,
    "IpAddress" character varying(64),
    CONSTRAINT "PK_OtpCodes" PRIMARY KEY ("Id")
);

CREATE TABLE IF NOT EXISTS "RefreshTokens" (
    "Id" uuid NOT NULL,
    "UserId" text NOT NULL,
    "TokenHash" character varying(128) NOT NULL,
    "ExpiresAt" timestamp with time zone NOT NULL,
    "CreatedAt" timestamp with time zone NOT NULL,
    "RevokedAt" timestamp with time zone,
    "ReplacedByTokenId" uuid,
    "DeviceInfo" character varying(300),
    "IpAddress" character varying(64),
    CONSTRAINT "PK_RefreshTokens" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_RefreshTokens_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS "PushSubscriptions" (
    "Id" uuid NOT NULL,
    "UserId" text NOT NULL,
    "DeviceToken" character varying(500) NOT NULL,
    "Platform" character varying(20) NOT NULL,
    "DeviceModel" character varying(200),
    "CreatedAt" timestamp with time zone NOT NULL,
    "LastSeenAt" timestamp with time zone NOT NULL,
    "IsActive" boolean NOT NULL,
    CONSTRAINT "PK_PushSubscriptions" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_PushSubscriptions_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS "Notifications" (
    "Id" uuid NOT NULL,
    "RecipientUserId" text NOT NULL,
    "Type" integer NOT NULL,
    "Title" character varying(200) NOT NULL,
    "Message" character varying(1000) NOT NULL,
    "LinkUrl" character varying(500),
    "IsRead" boolean NOT NULL,
    "CreatedAt" timestamp with time zone NOT NULL,
    "ReadAt" timestamp with time zone,
    CONSTRAINT "PK_Notifications" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_Notifications_AspNetUsers_RecipientUserId" FOREIGN KEY ("RecipientUserId") REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS "ChatMessages" (
    "Id" uuid NOT NULL,
    "SenderId" text NOT NULL,
    "ReceiverId" text NOT NULL,
    "Content" character varying(2000) NOT NULL,
    "IsRead" boolean NOT NULL,
    "SentAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_ChatMessages" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_ChatMessages_AspNetUsers_ReceiverId" FOREIGN KEY ("ReceiverId") REFERENCES "AspNetUsers" ("Id") ON DELETE RESTRICT,
    CONSTRAINT "FK_ChatMessages_AspNetUsers_SenderId" FOREIGN KEY ("SenderId") REFERENCES "AspNetUsers" ("Id") ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS "LeaveDays" (
    "Id" uuid NOT NULL,
    "BarberId" text NOT NULL,
    "LeaveDate" date NOT NULL,
    "Reason" character varying(300),
    "CreatedAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_LeaveDays" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_LeaveDays_AspNetUsers_BarberId" FOREIGN KEY ("BarberId") REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS "Services" (
    "Id" uuid NOT NULL,
    "Name" character varying(200) NOT NULL,
    "Description" character varying(1000),
    "Category" character varying(50) NOT NULL DEFAULT 'Hair',
    "Price" numeric(10,2) NOT NULL,
    "DurationMinutes" integer NOT NULL,
    "IsActive" boolean NOT NULL,
    "BarberId" text NOT NULL,
    "CreatedAt" timestamp with time zone NOT NULL,
    "UpdatedAt" timestamp with time zone,
    CONSTRAINT "PK_Services" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_Services_AspNetUsers_BarberId" FOREIGN KEY ("BarberId") REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS "Products" (
    "Id" uuid NOT NULL,
    "Name" character varying(200) NOT NULL,
    "Description" character varying(2000),
    "Price" numeric(10,2) NOT NULL,
    "DiscountPercentage" numeric(5,2),
    "StockQuantity" integer NOT NULL,
    "ImageUrl" text,
    "Category" character varying(100) NOT NULL,
    "IsActive" boolean NOT NULL,
    "BarberId" text,
    "CreatedAt" timestamp with time zone NOT NULL,
    "UpdatedAt" timestamp with time zone,
    "IsDeleted" boolean NOT NULL,
    "DeletedAt" timestamp with time zone,
    CONSTRAINT "PK_Products" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_Products_AspNetUsers_BarberId" FOREIGN KEY ("BarberId") REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS "CartItems" (
    "Id" uuid NOT NULL,
    "UserId" text NOT NULL,
    "ProductId" uuid NOT NULL,
    "Quantity" integer NOT NULL,
    "AddedAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_CartItems" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_CartItems_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_CartItems_Products_ProductId" FOREIGN KEY ("ProductId") REFERENCES "Products" ("Id") ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS "Orders" (
    "Id" uuid NOT NULL,
    "OrderNumber" character varying(50) NOT NULL,
    "UserId" text NOT NULL,
    "SubTotal" numeric(10,2) NOT NULL,
    "Tax" numeric(10,2) NOT NULL,
    "TotalAmount" numeric(10,2) NOT NULL,
    "Status" integer NOT NULL,
    "PaymentMethod" integer NOT NULL,
    "ShippingAddress" character varying(1000),
    "PaymentIntentId" character varying(200),
    "PaymentStatus" character varying(50),
    "CreatedAt" timestamp with time zone NOT NULL,
    "UpdatedAt" timestamp with time zone,
    CONSTRAINT "PK_Orders" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_Orders_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES "AspNetUsers" ("Id") ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS "OrderItems" (
    "Id" uuid NOT NULL,
    "OrderId" uuid NOT NULL,
    "ProductId" uuid NOT NULL,
    "ProductName" character varying(200) NOT NULL,
    "Quantity" integer NOT NULL,
    "UnitPrice" numeric(10,2) NOT NULL,
    CONSTRAINT "PK_OrderItems" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_OrderItems_Orders_OrderId" FOREIGN KEY ("OrderId") REFERENCES "Orders" ("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_OrderItems_Products_ProductId" FOREIGN KEY ("ProductId") REFERENCES "Products" ("Id") ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS "Bookings" (
    "Id" uuid NOT NULL,
    "UserId" text NOT NULL,
    "BarberId" text NOT NULL,
    "ServiceId" uuid NOT NULL,
    "AppointmentDate" date NOT NULL,
    "StartTime" time without time zone NOT NULL,
    "EndTime" time without time zone NOT NULL,
    "Status" integer NOT NULL,
    "Notes" character varying(1000),
    "RejectionReason" character varying(500),
    "TotalAmount" numeric(10,2) NOT NULL,
    "CreatedAt" timestamp with time zone NOT NULL,
    "UpdatedAt" timestamp with time zone,
    "LastQueuePositionNotified" integer,
    CONSTRAINT "PK_Bookings" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_Bookings_AspNetUsers_BarberId" FOREIGN KEY ("BarberId") REFERENCES "AspNetUsers" ("Id") ON DELETE RESTRICT,
    CONSTRAINT "FK_Bookings_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES "AspNetUsers" ("Id") ON DELETE RESTRICT,
    CONSTRAINT "FK_Bookings_Services_ServiceId" FOREIGN KEY ("ServiceId") REFERENCES "Services" ("Id") ON DELETE RESTRICT
);

